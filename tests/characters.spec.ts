import { expect, test } from '@playwright/test';

test('boy/girl settings persist with identical walking/casting and preserve the approved backdrop', async ({ page }) => {
  await page.goto('./');
  await expect(page.locator('#instructions')).toBeVisible();
  await page.locator('#student-appearance').selectOption('girl');
  await page.locator('#intro-language').selectOption('en');
  await expect(page.locator('#instructions [data-i18n="spellVisualNote"]')).toContainText('tiny blue ball');
  await expect(page.locator('#student-appearance')).toHaveValue('girl');
  await expect(page.locator('#appearance-preview')).toHaveAttribute('data-appearance', 'girl');
  await page.reload();
  await expect(page.locator('#instructions')).toBeVisible();
  await expect(page.locator('#student-appearance')).toHaveValue('girl');
  await page.locator('#start').click();
  await page.locator('[data-choice="continue"]').click();
  await page.locator('#interact').click();
  await page.locator('[data-choice="continue"]').click();
  await expect(page.locator('#scene')).toHaveAttribute('data-appearance', 'girl');
  await expect(page.locator('#scene')).toHaveAttribute('data-humans', 'frozen');
  await expect(page.locator('#scene')).toHaveAttribute('data-motion-spell-shape', 'SphereGeometry');
  await expect(page.locator('#scene')).toHaveAttribute('data-fire-spell-shape', 'SphereGeometry');
  const background = await page.locator('#scene').evaluate((element) => getComputedStyle(element).backgroundImage);
  expect(background).toContain('academy-background');
  const firstWingFrame = await page.locator('#scene').getAttribute('data-familiar-frame');
  await expect.poll(() => page.locator('#scene').getAttribute('data-familiar-frame')).not.toBe(firstWingFrame);
  await page.keyboard.down('d');
  await expect(page.locator('#scene')).toHaveAttribute('data-player-clip', 'walk');
  await page.screenshot({ path: test.info().outputPath('girl-walking.png') });
  await page.keyboard.up('d');
  await expect(page.locator('#scene')).toHaveAttribute('data-player-clip', 'idle');
  await page.locator('#execute').click();
  await expect(page.locator('#scene')).toHaveAttribute('data-player-clip', 'action');
  await expect(page.locator('#scene')).toHaveAttribute('data-player-frame', '3');
  const position = await page.locator('#scene').evaluate((element: HTMLElement) => [element.dataset.playerX, element.dataset.playerZ]);
  await page.screenshot({ path: test.info().outputPath('girl-casting.png') });
  expect(await page.locator('#scene').evaluate((element: HTMLElement) => [element.dataset.playerX, element.dataset.playerZ])).toEqual(position);
  await expect(page.locator('#phase')).toHaveText('Execution complete');
  await page.locator('#reset').click();
  await expect(page.locator('#scene')).toHaveAttribute('data-appearance', 'girl');
  await page.locator('#help').click();
  await expect(page.locator('#student-appearance')).toBeDisabled();
  await page.locator('#intro-language').selectOption('ko');
  await expect(page.locator('#student-appearance')).toHaveValue('girl');
  await page.locator('#start').click();
  await expect(page.locator('#scene')).toHaveAttribute('data-appearance', 'girl');
});

test('the glowing memory fragment opens the same bilingual memory and restores present position', async ({ page }) => {
  await page.goto('./');
  await page.locator('#intro-language').selectOption('en');
  await page.locator('#student-appearance').selectOption('girl');
  await page.locator('#start').click();
  await page.locator('[data-choice="continue"]').click();
  await page.locator('#interact').click();
  await page.locator('[data-choice="continue"]').click();
  await expect(page.locator('#scene')).toHaveAttribute('data-memory-object', 'fragment');
  await page.keyboard.down('a');
  await expect(page.locator('#interact')).toContainText('Examine the memory fragment');
  await page.keyboard.up('a');
  await expect(page.locator('#scene')).toHaveAttribute('data-player-clip', 'idle');
  const position = await page.locator('#scene').evaluate((element: HTMLElement) => [element.dataset.playerX, element.dataset.playerZ]);
  await page.screenshot({ path: test.info().outputPath('memory-fragment.png') });
  await page.locator('#interact').click();
  await expect(page.locator('#scene')).toHaveAttribute('data-chapter', 'memory');
  await expect(page.locator('#story-body')).toContainText('The fragment recalls a warm afternoon');
  await page.locator('#story-language').selectOption('ko');
  await expect(page.locator('#story-body')).toContainText('기억 조각');
  await expect(page.locator('#story-body')).not.toContainText('스카프');
  await page.locator('#story-language').selectOption('en');
  await page.locator('[data-choice="continue"]').click();
  await page.keyboard.down('w');
  await expect(page.locator('#interact')).toContainText('Speak with your friend');
  await page.keyboard.up('w');
  await page.locator('#interact').click();
  await page.locator('[data-choice="honest"]').click();
  await expect(page.locator('#scene')).toHaveAttribute('data-chapter', 'academy');
  await expect(page.locator('#scene')).toHaveAttribute('data-memory-object', 'none');
  await expect(page.locator('#scene')).toHaveAttribute('data-appearance', 'girl');
  expect(await page.locator('#scene').evaluate((element: HTMLElement) => [element.dataset.playerX, element.dataset.playerZ])).toEqual(position);
  await expect(page.locator('#stitches')).toHaveText('3 / 3');
});

test('missing girl artwork or academy backdrop reports an explicit localized loading error', async ({ page }) => {
  await page.route('**/characters/student-girl.png', (route) => route.abort());
  await page.goto('./');
  await expect(page.locator('#fatal-message')).toContainText('캐릭터 그림');
  await page.locator('#fatal-language').selectOption('en');
  await expect(page.locator('#fatal-message')).toContainText('Character artwork could not load');
  await page.unroute('**/characters/student-girl.png');
  await page.route('**/academy-background-*.webp', (route) => route.abort());
  await page.reload();
  await expect(page.locator('#fatal-message')).toContainText('academy backdrop could not load');
});
